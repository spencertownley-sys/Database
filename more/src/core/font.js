// MORE. — 8x8 bitmap font
// Glyphs marked (mockup) are copied pixel-for-pixel from the factory mockup.
// The rest were drawn to match: 7px wide, 2px vertical stems, 1px bars,
// row 7 reserved for descenders. 8px advance, 8px line.
