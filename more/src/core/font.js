  'use strict';

  const G = {};
  function def(ch, rows) {
    const out = [];
    for (let i = 0; i < 8; i++) out.push((rows[i] || '').padEnd(8, '.'));
    G[ch] = out;
  }

  // --- punctuation ------------------------------------------------------
  def(' ', []);
  def('!', ['..##', '..##', '..##', '..##', '..##', '', '..##']);
