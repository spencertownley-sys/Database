// Regenerates src/data/voicemail-data.js from assets/audio/ruth_voicemail.mp3.
// Embedding the clip as base64 lets the game decode it with WebAudio even when
// index.html is opened straight from disk (file://), where fetch() is blocked.
//
//   node tools/embed-voicemail.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mp3 = readFileSync(join(root, 'assets/audio/ruth_voicemail.mp3'));
const out = `// Generated by tools/embed-voicemail.mjs from assets/audio/ruth_voicemail.mp3. Do not edit.
(function (M) {
  M.VOICEMAIL_B64 = '${mp3.toString('base64')}';
})(window.MORE = window.MORE || {});
`;
writeFileSync(join(root, 'src/data/voicemail-data.js'), out);
console.log(`wrote src/data/voicemail-data.js (${mp3.length} bytes of audio)`);
